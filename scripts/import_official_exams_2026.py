def clean_text(s: str) -> str:
    if not s:
        return ""
    # Strip any trailing answer keys or separator lines or section markers
    cleaned = re.split(r"_{4,}|Sual\s*:\s*Cavab|===\s*.*?\s*===|(?:I|II|III)\s*B[ÖO]LM[ƏE].*", s, flags=re.IGNORECASE)[0]
    return cleaned.strip()

def escape_sql_str(s: str) -> str:
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"

def escape_sql_json(obj) -> str:
    if obj is None:
        return "NULL"
    json_str = json.dumps(obj, ensure_ascii=False)
    return "'" + json_str.replace("'", "''") + "'::jsonb"

def generate_sql() -> str:
    sql_lines = []
    sql_lines.append("-- ========================================================")
    sql_lines.append("-- Official Exams 2026 Import Script")
    sql_lines.append("-- Generated by import_official_exams_2026.py")
    sql_lines.append("-- ========================================================")
    sql_lines.append("BEGIN;")
    sql_lines.append("")

    total_quizzes = 0
    total_az_questions = 0
    total_ka_translations = 0

    target_quiz_ids = [f"'{item['quiz_id']}'" for item in EXAMS_MAP]
    quiz_ids_in_str = ", ".join(target_quiz_ids)

    # 1. Clean existing questions for only these 9 official quizzes
    sql_lines.append(f"-- 1. Remove old questions for the 9 official quizzes")
    sql_lines.append(f"DELETE FROM questions WHERE quiz_id IN ({quiz_ids_in_str});")
    sql_lines.append("")

    for item in EXAMS_MAP:
        quiz_id = item["quiz_id"]
        az_path = AZ_DIR / item["az_file"]
        ka_path = KA_DIR / item["ka_file"]

        if not az_path.exists():
            raise FileNotFoundError(f"Missing AZ file: {az_path}")
        if not ka_path.exists():
            raise FileNotFoundError(f"Missing KA file: {ka_path}")

        with open(az_path, "r", encoding="utf-8") as f:
            az_data = json.load(f)
        with open(ka_path, "r", encoding="utf-8") as f:
            ka_data = json.load(f)

        az_questions = az_data.get("questions", [])
        ka_questions = ka_data.get("questions", [])

        if len(az_questions) != 60 or len(ka_questions) != 60:
            raise ValueError(f"Exam {item['specialty_key']}: Expected 60 questions, got AZ={len(az_questions)}, KA={len(ka_questions)}")

        sql_lines.append(f"-- --------------------------------------------------------")
        sql_lines.append(f"-- Quiz: {item['title']} ({item['specialty_key']}) - {quiz_id}")
        sql_lines.append(f"-- --------------------------------------------------------")

        # Update quiz metadata
        pass_pct = az_data.get("pass_mark_pct", 50)
        duration = az_data.get("duration_minutes", 120)
        sql_lines.append(f"UPDATE quizzes SET question_count = 60, duration = {int(duration)}, pass_percentage = {int(pass_pct)}, updated_at = NOW() WHERE id = '{quiz_id}';")

        for idx, q_az in enumerate(az_questions):
            q_ka = ka_questions[idx]
            q_id = str(uuid.uuid4())
            order_idx = q_az.get("id", idx + 1)
            section = clean_text(q_az.get("section", ""))
            stem_az = clean_text(q_az.get("stem", ""))
            opts_az_dict = q_az.get("options", {})
            ans_key_az = q_az.get("answer", "A")
            rationale_az = clean_text(q_az.get("rationale", ""))

            # Clean options [A, B, C, D, E]
            cleaned_opts_az = {k: clean_text(v) for k, v in opts_az_dict.items()}
            options_az_list = [
                cleaned_opts_az.get("A", ""),
                cleaned_opts_az.get("B", ""),
                cleaned_opts_az.get("C", ""),
                cleaned_opts_az.get("D", ""),
                cleaned_opts_az.get("E", ""),
            ]
            correct_ans_az = cleaned_opts_az.get(ans_key_az, "")

            # Georgian counterpart
            stem_ka = clean_text(q_ka.get("stem", ""))
            opts_ka_dict = q_ka.get("options", {})
            ans_key_ka = q_ka.get("answer", ans_key_az)
            rationale_ka = clean_text(q_ka.get("rationale", ""))
            cleaned_opts_ka = {k: clean_text(v) for k, v in opts_ka_dict.items()}
            options_ka_list = [
                cleaned_opts_ka.get("A", ""),
                cleaned_opts_ka.get("B", ""),
                cleaned_opts_ka.get("C", ""),
                cleaned_opts_ka.get("D", ""),
                cleaned_opts_ka.get("E", ""),
            ]
            correct_ans_ka = cleaned_opts_ka.get(ans_key_ka, "")

            # Insert question
            sql_lines.append(
                f"INSERT INTO questions ("
                f"id, quiz_id, question_text, question_type, options, correct_answer, explanation, topic, order_index, "
                f"is_required, shuffle_options, is_graded, weight, answer_match_type, answer_trim_spaces, answer_case_sensitive, created_at"
                f") VALUES ("
                f"'{q_id}', '{quiz_id}', {escape_sql_str(stem_az)}, 'multiple_choice', {escape_sql_json(options_az_list)}, "
                f"{escape_sql_str(correct_ans_az)}, {escape_sql_str(rationale_az)}, {escape_sql_str(section)}, {order_idx}, "
                f"true, false, true, 1.0, 'exact', true, false, NOW()"
                f");"
            )
            total_az_questions += 1

            # Insert Georgian translation
            trans_id = str(uuid.uuid4())
            sql_lines.append(
                f"INSERT INTO question_translations ("
                f"id, question_id, language_code, question_text, options, correct_answer, explanation, created_at, updated_at"
                f") VALUES ("
                f"'{trans_id}', '{q_id}', 'ka', {escape_sql_str(stem_ka)}, {escape_sql_json(options_ka_list)}, "
                f"{escape_sql_str(correct_ans_ka)}, {escape_sql_str(rationale_ka)}, NOW(), NOW()"
                f");"
            )
            total_ka_translations += 1

        total_quizzes += 1

    sql_lines.append("")
    sql_lines.append("COMMIT;")
    sql_lines.append("")
    sql_lines.append(f"-- Total Quizzes updated: {total_quizzes}")
    sql_lines.append(f"-- Total AZ Questions inserted: {total_az_questions}")
    sql_lines.append(f"-- Total KA Translations inserted: {total_ka_translations}")

    return "\n".join(sql_lines)

if __name__ == "__main__":
    sql_output_file = "/srv/quizspark-azeri/scripts/import_official_exams_2026.sql"
    sql_content = generate_sql()
    with open(sql_output_file, "w", encoding="utf-8") as f:
        f.write(sql_content)
    print(f"SQL migration script successfully generated: {sql_output_file}")
