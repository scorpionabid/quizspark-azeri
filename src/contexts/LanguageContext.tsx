const LanguageContext = createContext<LanguageContextType>({
  language: 'az',
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

const VALID_LANGS: AppLanguage[] = ['az', 'ka', 'ru', 'tr', 'en'];

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('quiz_language') as AppLanguage | null;
      if (saved && VALID_LANGS.includes(saved)) return saved;
    }
    return 'az';
  });

  const setLanguage = (lang: AppLanguage) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('quiz_language', lang);
      window.dispatchEvent(new Event('storage'));
    }
  };

  useEffect(() => {
    const handleStorage = () => {
      const saved = localStorage.getItem('quiz_language') as AppLanguage | null;
      if (saved && VALID_LANGS.includes(saved)) {
        setLanguageState(saved);
      }
    };
    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, []);

  const t = (key: string, fallback?: string): string => {
    const langDict = UI_TRANSLATIONS[language];
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    const fallbackDict = UI_TRANSLATIONS.az;
    if (fallbackDict && fallbackDict[key] !== undefined) {
      return fallbackDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
